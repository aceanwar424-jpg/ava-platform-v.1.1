// OWNED_BY: generic. Offline reproducible standards snapshot, licensed primary terms and validated UCUM units.
const fs = require("node:fs"),
  {
    readSeedSources,
    normalizeUnit,
    hash,
  } = require("../lib/catalog/seed_catalog"),
  { validateUcum } = require("../lib/catalog/ucum_validation");
const m = JSON.parse(
    fs.readFileSync("data/catalog/loinc_primary_metadata.json", "utf8"),
  ),
  terms = m.terms.filter((t) => t.lookup_status === "FOUND");
const s = readSeedSources(
  Array.from({ length: 8 }, (_, i) => {
    const file =
      "ava-platform/sql_arsip/06_seed_data/supabase_seed_part0" +
      (i + 1) +
      ".sql";
    return { file, text: fs.readFileSync(file, "utf8") };
  }),
);
const common = [
  "g/L",
  "g/dL",
  "mg/L",
  "mg/dL",
  "ug/L",
  "ug/dL",
  "ng/L",
  "ng/mL",
  "pg/mL",
  "mol/L",
  "mmol/L",
  "umol/L",
  "nmol/L",
  "pmol/L",
  "1",
  "%",
  "10*3/uL",
  "10*6/uL",
  "10*9/L",
  "[IU]/L",
  "[IU]/mL",
  "m[IU]/mL",
  "u[IU]/mL",
  "U/L",
  "U/mL",
  "min",
  "s",
  "ms",
  "mm/h",
];
const candidates = [
  ...new Set([
    ...common,
    ...s.items.map((i) => normalizeUnit(i.source_unit)).filter(Boolean),
    ...terms.flatMap((t) => (t.units || []).map((u) => u.unit)),
  ]),
].sort();
const units = candidates
  .map((code) => ({
    code,
    validation: {
      ...validateUcum(code),
      validator: "NLM @lhncbc/ucum-lhc",
      validator_version: "7.1.9",
    },
  }))
  .filter(
    (u) => u.validation.status === "valid" && u.validation.ucumCode === u.code,
  );
const quote = (v) => "'" + String(v).replace(/'/g, "''") + "'";
const lines = [
  "-- OWNED_BY: generic standards snapshot. Generated by build_catalog_terminology_migration.cjs.",
  "-- LOINC copyright Regenstrief Institute and LOINC Committee; https://loinc.org/license.",
  "-- UCUM copyright Regenstrief Institute and UCUM Organization; NLM validator license in data/catalog/UCUM_LHC_LICENSE.md.",
  "-- API distribution version unavailable; access date and digests retained, no automatic clinical matching/ranges.",
  "BEGIN;",
];
for (const term of terms)
  lines.push(
    "INSERT INTO lis_catalog_primary_terms(code,primary_name,metadata) VALUES(" +
      [
        quote(term.code),
        quote(term.long_name),
        quote(JSON.stringify(term)) + "::jsonb",
      ].join(",") +
      ");",
  );
for (const unit of units)
  lines.push(
    "INSERT INTO lis_catalog_ucum_units(code,validation) VALUES(" +
      quote(unit.code) +
      "," +
      quote(JSON.stringify(unit.validation)) +
      "::jsonb);",
  );
lines.push("COMMIT;", "");
fs.writeFileSync(
  "db/migrations/0106_catalog_primary_terminology_snapshot.sql",
  lines.join("\n"),
);
fs.writeFileSync(
  "data/catalog/ucum_validated_units.json",
  JSON.stringify(
    {
      owned_by: "generic",
      validator: "NLM @lhncbc/ucum-lhc 7.1.9",
      note: "Validation only; no patient-value conversions or clinical reference defaults.",
      units,
      source_sha256: hash(m),
      license: "UCUM_LHC_LICENSE.md",
    },
    null,
    2,
  ) + "\n",
);
fs.copyFileSync(
  "lib/catalog/node_modules/@lhncbc/ucum-lhc/LICENSE.md",
  "data/catalog/UCUM_LHC_LICENSE.md",
);
console.log(
  terms.length +
    " source terms and " +
    units.length +
    " validated UCUM units; reproducible offline migration",
);
